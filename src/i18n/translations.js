translations.en = Object.fromEntries(
  Object.keys(translations.hi || {}).map((key) => [key, key])
)

export const supportedLanguages = [
  { code: 'en', name: 'English' },
  { code: 'hi', name: 'हिन्दी' },
  { code: 'mr', name: 'मराठी' }
]

export function translateText(text, language) {
  if (typeof text !== 'string' || !text) return text

  const validLanguage = supportedLanguages.some(({ code }) => code === language) ? language : 'en'
  const dictionary = translations[validLanguage] || translations.en || {}

  const leadingWhitespace = text.match(/^\s*/)?.[0] || ''
  const trailingWhitespace = text.match(/\s*$/)?.[0] || ''
  const content = text.slice(leadingWhitespace.length, text.length - trailingWhitespace.length || undefined)
  const exact = dictionary[content]
  return `${leadingWhitespace}${exact || content}${trailingWhitespace}`
}
